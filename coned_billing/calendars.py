"""Con Edison holiday calendars (R2, WP2).

Holidays are generated by rule for any year; nothing is cached for a fixed
range. Dates are New York civil dates. Each named :class:`HolidaySet` cites the
tariff leaf that defines it, because Con Edison's holiday lists differ by rate
and season. No observed-day shift (e.g. July 4 on a Sunday observed on Monday)
is applied: none of the cited leaves provides one.

Source document: PSC No. 10 - Electricity, full tariff PDF retrieved
2026-10-23 from coned.com (``electric-tariff.pdf``, sha256 ``4141be1f...cb851f``).
"""

from __future__ import annotations

import calendar
from collections.abc import Iterable
from dataclasses import dataclass
from datetime import date, datetime
from enum import StrEnum
from typing import overload

import numpy as np
import pandas as pd

from .errors import ConEdBillingError

__all__ = [
    "HOLIDAY_SETS",
    "TARIFF_TZ",
    "Holiday",
    "HolidaySet",
    "get_holiday_set",
    "holiday_date",
    "is_coned_holiday",
]

TARIFF_TZ = "America/New_York"


class Holiday(StrEnum):
    """Holidays named in Con Edison's PSC No. 10 rate text."""

    NEW_YEARS_DAY = "new_years_day"  # January 1
    MEMORIAL_DAY = "memorial_day"  # last Monday in May
    INDEPENDENCE_DAY = "independence_day"  # July 4
    LABOR_DAY = "labor_day"  # first Monday in September
    THANKSGIVING_DAY = "thanksgiving_day"  # fourth Thursday in November
    CHRISTMAS_DAY = "christmas_day"  # December 25


def _nth_weekday(year: int, month: int, weekday: int, n: int) -> date:
    """n-th (1-based) given weekday of a month; n=-1 for the last one."""
    days = [
        d
        for d in calendar.Calendar().itermonthdates(year, month)
        if d.month == month and d.weekday() == weekday
    ]
    return days[n - 1] if n > 0 else days[n]


def holiday_date(holiday: Holiday | str, year: int) -> date:
    """Civil date of ``holiday`` in ``year`` (no observed-day shift)."""
    h = Holiday(holiday)
    if not isinstance(year, int) or isinstance(year, bool) or not 1900 <= year <= 2200:
        raise ConEdBillingError(f"year must be an integer in 1900..2200, got {year!r}")
    match h:
        case Holiday.NEW_YEARS_DAY:
            return date(year, 1, 1)
        case Holiday.MEMORIAL_DAY:
            return _nth_weekday(year, 5, calendar.MONDAY, -1)
        case Holiday.INDEPENDENCE_DAY:
            return date(year, 7, 4)
        case Holiday.LABOR_DAY:
            return _nth_weekday(year, 9, calendar.MONDAY, 1)
        case Holiday.THANKSGIVING_DAY:
            return _nth_weekday(year, 11, calendar.THURSDAY, 4)
        case Holiday.CHRISTMAS_DAY:
            return date(year, 12, 25)
    raise AssertionError(h)  # pragma: no cover


@dataclass(frozen=True, slots=True)
class HolidaySet:
    """A named set of holidays with the tariff text that defines it."""

    name: str
    holidays: frozenset[Holiday]
    source: str

    def dates(self, start_year: int, end_year: int) -> frozenset[date]:
        """All holiday dates in ``start_year..end_year`` inclusive."""
        return frozenset(
            holiday_date(h, y) for y in range(start_year, end_year + 1) for h in self.holidays
        )

    @overload
    def contains(self, when: pd.Timestamp | datetime | date) -> bool: ...
    @overload
    def contains(self, when: pd.DatetimeIndex | Iterable) -> np.ndarray: ...
    def contains(self, when):
        """Whether the New York civil date of ``when`` is in this set.

        A scalar (``date``, ``datetime`` or ``Timestamp``) returns ``bool``; a
        ``DatetimeIndex`` or array-like returns a boolean ``numpy`` array.
        Timezone-aware times are converted to New York first; naive times are
        taken as New York wall-clock times.
        """
        if isinstance(when, date) and not isinstance(when, datetime):
            return when in self.dates(when.year, when.year)
        if isinstance(when, datetime):  # includes pd.Timestamp
            ts = pd.Timestamp(when)
            if ts.tz is not None:
                ts = ts.tz_convert(TARIFF_TZ)
            d = ts.date()
            return d in self.dates(d.year, d.year)
        idx = pd.DatetimeIndex(when)
        if len(idx) == 0:
            return np.zeros(0, dtype=bool)
        if idx.tz is not None:
            idx = idx.tz_convert(TARIFF_TZ)
        local = idx.tz_localize(None) if idx.tz is not None else idx
        if not self.holidays:
            return np.zeros(len(idx), dtype=bool)
        years = local.year
        lookup = pd.DatetimeIndex(sorted(self.dates(int(years.min()), int(years.max()))))
        return np.asarray(local.normalize().isin(lookup), dtype=bool)


_SIX = frozenset(Holiday)

