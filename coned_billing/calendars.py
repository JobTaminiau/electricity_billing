def get_holiday_set(spec: str | Iterable[str] | HolidaySet) -> HolidaySet:
    """Resolve a set name, a list of :class:`Holiday` names, or a HolidaySet."""
    if isinstance(spec, HolidaySet):
        return spec
    if isinstance(spec, str):
        try:
            return HOLIDAY_SETS[spec]
        except KeyError:
            raise ConEdBillingError(
                f"unknown holiday set {spec!r}; known: {sorted(HOLIDAY_SETS)}"
            ) from None
    names = list(spec)
    try:
        members = frozenset(Holiday(n) for n in names)
    except ValueError:
        bad = [n for n in names if n not in {h.value for h in Holiday}]
        raise ConEdBillingError(
            f"unknown holiday name(s) {bad}; known: {[h.value for h in Holiday]}"
        ) from None
    if len(members) != len(names):
        raise ConEdBillingError(f"duplicate holiday names in {names}")
    return HolidaySet(
        "custom:" + ",".join(sorted(m.value for m in members)), members, "user-defined"
    )


@overload
def is_coned_holiday(
    when: pd.Timestamp | datetime | date, holiday_set: str | HolidaySet = ...
) -> bool: ...
@overload
def is_coned_holiday(
    when: pd.DatetimeIndex | Iterable, holiday_set: str | HolidaySet = ...
) -> np.ndarray: ...
def is_coned_holiday(when, holiday_set="coned_six"):
    """Holiday membership in New York civil time (default: the six-day set).

    Scalars return ``bool``; a DatetimeIndex or array-like returns a boolean
    ``numpy`` array. See :meth:`HolidaySet.contains`.
    """
    return get_holiday_set(holiday_set).contains(when)
